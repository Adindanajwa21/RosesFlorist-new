create table if not exists public.products (
    id bigint generated by default as identity primary key,
    code text not null unique,
    name text not null,
    category text not null,
    price integer not null check (price > 0),
    size text not null,
    image_url text,
    description text not null,
    materials text,
    height_estimate text,
    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.orders (
    id bigint generated by default as identity primary key,
    product_id bigint references public.products(id) on delete set null,
    order_type text not null default 'Produk katalog',
    product_name text not null,
    customer_name text,
    phone text,
    details text,
    created_at timestamptz not null default now()
);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

drop trigger if exists products_set_updated_at on public.products;
create trigger products_set_updated_at
before update on public.products
for each row execute function public.set_updated_at();

-- Ganti email ini bila email admin Anda berbeda, lalu jalankan ulang bagian policy.
create or replace function public.is_store_admin()
returns boolean
language sql
stable
as $$
    select coalesce(auth.jwt() ->> 'email', '') = 'admin@rosesflorist.com';
$$;

alter table public.products enable row level security;
alter table public.orders enable row level security;

drop policy if exists "Public can read active products" on public.products;
create policy "Public can read active products"
on public.products for select
using (is_active = true or public.is_store_admin());

drop policy if exists "Admin manages products" on public.products;
create policy "Admin manages products"
on public.products for all
using (public.is_store_admin())
with check (public.is_store_admin());

drop policy if exists "Public can create orders" on public.orders;
create policy "Public can create orders"
on public.orders for insert
with check (true);

drop policy if exists "Admin reads orders" on public.orders;
create policy "Admin reads orders"
on public.orders for select
using (public.is_store_admin());

drop policy if exists "Admin deletes orders" on public.orders;
create policy "Admin deletes orders"
on public.orders for delete
using (public.is_store_admin());

insert into storage.buckets (id, name, public)
values ('product-images', 'product-images', true)
on conflict (id) do update set public = true;

drop policy if exists "Public reads product images" on storage.objects;
create policy "Public reads product images"
on storage.objects for select
using (bucket_id = 'product-images');

drop policy if exists "Admin uploads product images" on storage.objects;
create policy "Admin uploads product images"
on storage.objects for insert
with check (bucket_id = 'product-images' and public.is_store_admin());

drop policy if exists "Admin updates product images" on storage.objects;
create policy "Admin updates product images"
on storage.objects for update
using (bucket_id = 'product-images' and public.is_store_admin())
with check (bucket_id = 'product-images' and public.is_store_admin());

drop policy if exists "Admin deletes product images" on storage.objects;
create policy "Admin deletes product images"
on storage.objects for delete
using (bucket_id = 'product-images' and public.is_store_admin());
